package com.labmentix.speechmatrix.security;

import lombok.extern.slf4j.Slf4j;
import org.springframework.security.crypto.bcrypt.BCrypt;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.stereotype.Service;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Centralises all BCrypt operations and exposes password-strength
 * analysis for the /api/auth/password-info diagnostic endpoint.
 *
 * BCrypt facts:
 *  - Cost factor (strength) 10 = ~100ms per hash on a modern CPU
 *  - Cost factor 12 = ~400ms â?? recommended for production
 *  - Each hash is salted randomly â?? same password â?? different hash every time
 *  - Maximum input length is 72 bytes (BCrypt limitation)
 *  - Output is always 60 chars: $2a$<cost>$<22-char-salt><31-char-hash>
 */
@Service
@Slf4j
public class BCryptPasswordService {

    // Cost 12 for production security; reduce to 10 in tests for speed
    private static final int    BCRYPT_STRENGTH  = 12;
    private static final int    MAX_INPUT_BYTES  = 72;

    private final BCryptPasswordEncoder encoder =
            new BCryptPasswordEncoder(BCRYPT_STRENGTH);

    // â??â?? Core operations â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /** Hash a plain-text password. Never store the plain-text. */
    public String hash(String rawPassword) {
        validateLength(rawPassword);
        long start  = System.currentTimeMillis();
        String hash = encoder.encode(rawPassword);
        log.debug("BCrypt hash (strength {}) took {}ms",
                  BCRYPT_STRENGTH, System.currentTimeMillis() - start);
        return hash;
    }

    /** Verify a plain-text password against a stored BCrypt hash. */
    public boolean verify(String rawPassword, String storedHash) {
        if (rawPassword == null || storedHash == null) return false;
        return encoder.matches(rawPassword, storedHash);
    }

    /**
     * Check if a stored hash needs to be re-hashed.
     * Useful when you increase the cost factor in a future release â??
     * rehash on next successful login without forcing password resets.
     */
    public boolean needsUpgrade(String storedHash) {
        return encoder.upgradeEncoding(storedHash);
    }

    // â??â?? Diagnostics (useful during development) â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /**
     * Returns a map of BCrypt metadata for a given password.
     * Exposed via GET /api/auth/password-info?password=... (dev only).
     */
    public Map<String, Object> analyzePassword(String rawPassword) {
        Map<String, Object> info = new LinkedHashMap<>();

        // â??â?? Input analysis â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
        int byteLength = rawPassword.getBytes(java.nio.charset.StandardCharsets.UTF_8).length;
        info.put("inputLength",    rawPassword.length());
        info.put("inputByteSize",  byteLength);
        info.put("exceedsMaxBytes",byteLength > MAX_INPUT_BYTES);
        info.put("maxBytesNote",   "BCrypt truncates input at 72 bytes");

        // â??â?? Strength rules â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
        info.put("hasMinLength",   rawPassword.length() >= 8);
        info.put("hasUppercase",   rawPassword.matches(".*[A-Z].*"));
        info.put("hasLowercase",   rawPassword.matches(".*[a-z].*"));
        info.put("hasDigit",       rawPassword.matches(".*\\d.*"));
        info.put("hasSpecialChar", rawPassword.matches(".*[!@#$%^&*()_+\\-=\\[\\]{};':\"\\\\|,.<>/?].*"));

        // â??â?? Hash demonstration â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
        long start    = System.currentTimeMillis();
        String hash1  = encoder.encode(rawPassword);
        long   time1  = System.currentTimeMillis() - start;

        start         = System.currentTimeMillis();
        String hash2  = encoder.encode(rawPassword);
        long   time2  = System.currentTimeMillis() - start;

        info.put("hash1",              hash1);
        info.put("hash2",              hash2);
        info.put("hashesAreDifferent", !hash1.equals(hash2)); // always true â?? random salt
        info.put("hashLength",         hash1.length());       // always 60
        info.put("hash1TimeMs",        time1);
        info.put("hash2TimeMs",        time2);
        info.put("bcryptStrength",     BCRYPT_STRENGTH);
        info.put("hashPrefix",         hash1.substring(0, 7)); // e.g. "$2a$12$"

        // â??â?? Verification demo â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
        info.put("hash1VerifiesOk",  encoder.matches(rawPassword, hash1));
        info.put("hash2VerifiesOk",  encoder.matches(rawPassword, hash2));

        return info;
    }

    // â??â?? Private â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    private void validateLength(String rawPassword) {
        if (rawPassword == null) throw new IllegalArgumentException("Password cannot be null");
        int bytes = rawPassword.getBytes(java.nio.charset.StandardCharsets.UTF_8).length;
        if (bytes > MAX_INPUT_BYTES) {
            log.warn("Password exceeds BCrypt 72-byte limit ({} bytes). " +
                     "Characters beyond byte 72 will be silently ignored.", bytes);
        }
    }
}
