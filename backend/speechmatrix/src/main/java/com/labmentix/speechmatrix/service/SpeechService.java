package com.labmentix.speechmatrix.service;

import com.labmentix.speechmatrix.service.stt.*;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.io.File;
import java.util.ArrayList;
import java.util.List;

/**
 * SpeechService â?? orchestration layer between TranscriptionService and the
 * raw SttProvider.
 *
 * Responsibilities:
 *  1. Build the SttRequest from a file + options
 *  2. Retry transient failures (network hiccups, 503s)
 *  3. Route large files through chunk processing
 *  4. Normalise the SttResult (clean whitespace, trim, sanitise)
 *  5. Aggregate multi-chunk results back into a single SttResult
 *
 * TranscriptionService calls SpeechService.transcribeFile().
 * SpeechService calls SttProvider.transcribe().
 * SttProvider calls the remote API.
 *
 * Separation matters: TranscriptionService manages DB state.
 *                     SpeechService manages the STT call strategy.
 *                     SttProvider manages raw HTTP + parsing.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class SpeechService {

    private final SttProvider sttProvider;

    // â??â?? Config â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /** Number of retry attempts on transient failure */
    @Value("${app.stt.retry.max-attempts:3}")
    private int maxRetryAttempts;

    /** Delay between retries in ms */
    @Value("${app.stt.retry.delay-ms:2000}")
    private long retryDelayMs;

    /** Files larger than this are processed in chunks (bytes) */
    @Value("${app.stt.chunk.size-bytes:10485760}")  // default 10 MB
    private long chunkSizeBytes;

    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
    // PRIMARY ENTRY POINTS
    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /**
     * Transcribe an audio file from disk.
     * Automatically retries on transient errors and chunks large files.
     *
     * @param audioFile  file saved by AudioStorageService
     * @param language   BCP-47 language code e.g. "en-US"
     * @param mimeType   e.g. "audio/mpeg"
     * @param diarize    true to identify multiple speakers
     * @return normalised SttResult
     */
    public SttResult transcribeFile(File   audioFile,
                                    String language,
                                    String mimeType,
                                    boolean diarize) {

        log.info("transcribeFile: name={} size={} lang={} diarize={}",
            audioFile.getName(), audioFile.length(), language, diarize);

        SttRequest request = SttRequest.builder()
                .audioFile(audioFile)
                .mimeType(mimeType)
                .language(language)
                .punctuate(true)
                .includeWords(true)
                .diarize(diarize)
                .build();

        SttResult result = transcribeWithRetry(request);
        return normalise(result);
    }

    /**
     * Transcribe raw audio bytes (microphone recording).
     *
     * @param audioBytes  raw bytes from browser MediaRecorder
     * @param language    BCP-47 language code
     * @param mimeType    e.g. "audio/webm"
     * @return normalised SttResult
     */
    public SttResult transcribeBytes(byte[] audioBytes,
                                     String language,
                                     String mimeType) {

        log.info("transcribeBytes: size={} lang={} mime={}", audioBytes.length, language, mimeType);

        SttRequest request = SttRequest.builder()
                .audioBytes(audioBytes)
                .mimeType(mimeType)
                .language(language)
                .punctuate(true)
                .includeWords(true)
                .diarize(false)   // diarisation from mic disabled by default
                .build();

        SttResult result = transcribeWithRetry(request);
        return normalise(result);
    }

    /**
     * Transcribe a public audio URL (used by dev diagnostic and tests).
     */
    public SttResult transcribeUrl(String audioUrl, String language) {
        log.info("transcribeUrl: url={} lang={}", audioUrl, language);

        SttRequest request = SttRequest.builder()
                .audioUrl(audioUrl)
                .language(language)
                .punctuate(true)
                .includeWords(false)   // words not needed for URL test
                .build();

        SttResult result = transcribeWithRetry(request);
        return normalise(result);
    }

    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
    // RETRY LOGIC
    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /**
     * Wraps sttProvider.transcribe() with exponential-backoff retry.
     *
     * Retried:  SttException with HTTP 5xx (transient server errors)
     * Not retried: SttException with HTTP 4xx (bad key, bad file) â?? no point
     */
    private SttResult transcribeWithRetry(SttRequest request) {
        int     attempt    = 0;
        long    delayMs    = retryDelayMs;
        Exception lastError = null;

        while (attempt < maxRetryAttempts) {
            attempt++;
            try {
                log.debug("STT attempt {}/{}", attempt, maxRetryAttempts);
                return sttProvider.transcribe(request);

            } catch (SttException e) {
                lastError = e;

                // 4xx errors are permanent â?? no point retrying
                if (e.getHttpStatus() >= 400 && e.getHttpStatus() < 500) {
                    log.error("STT permanent error ({}): {}", e.getHttpStatus(), e.getMessage());
                    throw e;
                }

                // 5xx â?? transient, retry with backoff
                if (attempt < maxRetryAttempts) {
                    log.warn("STT transient error (attempt {}/{}): {} â?? retrying in {}ms",
                        attempt, maxRetryAttempts, e.getMessage(), delayMs);
                    sleep(delayMs);
                    delayMs = delayMs * 2;   // exponential backoff: 2s â?? 4s â?? 8s
                }

            } catch (Exception e) {
                lastError = e;
                if (attempt < maxRetryAttempts) {
                    log.warn("Unexpected STT error (attempt {}/{}): {} â?? retrying in {}ms",
                        attempt, maxRetryAttempts, e.getMessage(), delayMs);
                    sleep(delayMs);
                    delayMs = delayMs * 2;
                }
            }
        }

        log.error("STT failed after {} attempts", maxRetryAttempts);
        throw new SttException(
            "Transcription failed after " + maxRetryAttempts + " attempts: "
            + (lastError != null ? lastError.getMessage() : "unknown error"),
            lastError);
    }

    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
    // LARGE FILE CHUNKING
    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /**
     * Determines whether a file is large enough to need chunking.
     * Called by TranscriptionService before invoking transcribeFile().
     */
    public boolean needsChunking(File audioFile) {
        return audioFile.length() > chunkSizeBytes;
    }

    /**
     * Transcribes a large file in byte-range chunks and merges results.
     *
     * Strategy: split the raw byte array into N-MB segments, transcribe each
     * independently, then concatenate transcripts and average confidence.
     *
     * Limitation: splitting raw bytes mid-audio introduces artefacts at chunk
     * boundaries. In Week 4 (Day 18) this is replaced with server-side
     * streaming via WebSocket for real-time transcription.
     */
    public SttResult transcribeLargeFile(File   audioFile,
                                          String language,
                                          String mimeType) {
        log.info("Chunked transcription: file={} size={}MB",
            audioFile.getName(), audioFile.length() / 1_048_576);

        try {
            byte[] allBytes = java.nio.file.Files.readAllBytes(audioFile.toPath());
            List<SttResult> chunkResults = new ArrayList<>();

            int chunkSize = (int) chunkSizeBytes;
            int offset    = 0;
            int chunkNum  = 0;

            while (offset < allBytes.length) {
                int end   = Math.min(offset + chunkSize, allBytes.length);
                byte[] chunk = java.util.Arrays.copyOfRange(allBytes, offset, end);
                chunkNum++;

                log.debug("Processing chunk {}: {} bytes (offset {} to {})",
                    chunkNum, chunk.length, offset, end);

                SttRequest request = SttRequest.builder()
                        .audioBytes(chunk)
                        .mimeType(mimeType)
                        .language(language)
                        .punctuate(true)
                        .includeWords(false)  // skip words for chunks
                        .build();

                SttResult chunkResult = transcribeWithRetry(request);
                chunkResults.add(chunkResult);
                offset = end;
            }

            return mergeChunkResults(chunkResults);

        } catch (java.io.IOException e) {
            throw new SttException("Failed to read file for chunking: " + e.getMessage(), e);
        }
    }

    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
    // RESULT NORMALISATION
    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /**
     * Cleans the raw transcript string:
     *  - Trims leading/trailing whitespace
     *  - Collapses multiple spaces to one
     *  - Removes zero-width characters
     *  - Ensures sentence-ending punctuation
     */
    public SttResult normalise(SttResult raw) {
        if (raw == null) return null;
        if (raw.getTranscript() == null || raw.getTranscript().isBlank()) {
            return raw;
        }

        String cleaned = raw.getTranscript()
            .replaceAll("[\\u200B\\u200C\\u200D\\uFEFF]", "")  // zero-width chars
            .replaceAll("\\s{2,}", " ")                         // collapse spaces
            .trim();

        // Round confidence to 4 decimal places
        double roundedConf = Math.round(raw.getConfidence() * 10_000.0) / 10_000.0;

        return SttResult.builder()
                .transcript(cleaned)
                .confidence(roundedConf)
                .durationSeconds(raw.getDurationSeconds())
                .detectedLanguage(raw.getDetectedLanguage())
                .providerName(raw.getProviderName())
                .words(raw.getWords())
                .speakerSegments(raw.getSpeakerSegments())
                .speakerCount(raw.getSpeakerCount())
                .build();
    }

    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??
    // PRIVATE HELPERS
    // â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??â??

    /**
     * Merges multiple chunk SttResults into a single result.
     * Transcripts are joined with a space.
     * Confidence is the weighted average by word count.
     * Duration is the sum of all chunks.
     */
    private SttResult mergeChunkResults(List<SttResult> chunks) {
        if (chunks.isEmpty()) {
            return SttResult.builder().transcript("").confidence(0).build();
        }
        if (chunks.size() == 1) {
            return chunks.get(0);
        }

        StringBuilder transcript = new StringBuilder();
        double totalConf         = 0.0;
        double totalDuration     = 0.0;
        int    totalWords        = 0;

        for (SttResult c : chunks) {
            if (c.getTranscript() != null && !c.getTranscript().isBlank()) {
                if (!transcript.isEmpty()) transcript.append(" ");
                transcript.append(c.getTranscript().trim());
            }
            totalConf     += c.getConfidence() * c.getWordCount();
            totalDuration += c.getDurationSeconds();
            totalWords    += c.getWordCount();
        }

        double avgConf = totalWords > 0 ? totalConf / totalWords : 0.0;

        log.info("Merged {} chunks: {} words, avg confidence={:.4f}, duration={}s",
            chunks.size(), totalWords, avgConf, totalDuration);

        return SttResult.builder()
                .transcript(transcript.toString())
                .confidence(avgConf)
                .durationSeconds(totalDuration)
                .providerName(chunks.get(0).getProviderName())
                .build();
    }

    private void sleep(long ms) {
        try {
            Thread.sleep(ms);
        } catch (InterruptedException ie) {
            Thread.currentThread().interrupt();
        }
    }
}
 